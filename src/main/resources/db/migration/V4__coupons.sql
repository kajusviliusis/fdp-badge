CREATE TABLE coupons (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(50)    NOT NULL,
    discount_type    VARCHAR(20)    NOT NULL,
    discount_value   NUMERIC(10, 2) NOT NULL,
    max_discount     NUMERIC(10, 2),
    min_order_amount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    valid_from       TIMESTAMP WITH TIME ZONE,
    valid_until      TIMESTAMP WITH TIME ZONE,
    usage_limit      INTEGER,
    times_used       INTEGER        NOT NULL DEFAULT 0,
    active           BOOLEAN        NOT NULL DEFAULT TRUE,
    version          BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_coupons_code UNIQUE (code),
    CONSTRAINT ck_coupons_code_upper CHECK (code = upper(code)),
    CONSTRAINT ck_coupons_type CHECK (discount_type IN ('FIXED', 'PERCENT')),
    CONSTRAINT ck_coupons_value CHECK (discount_value > 0 AND (discount_type = 'FIXED' OR discount_value <= 100)),
    CONSTRAINT ck_coupons_usage CHECK (times_used >= 0 AND (usage_limit IS NULL OR usage_limit > 0))
);

ALTER TABLE orders
    ADD COLUMN coupon_id BIGINT,
    ADD COLUMN coupon_discount NUMERIC(10, 2) NOT NULL DEFAULT 0,
    ADD CONSTRAINT fk_orders_coupon FOREIGN KEY (coupon_id) REFERENCES coupons (id);

CREATE INDEX idx_orders_coupon ON orders (coupon_id);

