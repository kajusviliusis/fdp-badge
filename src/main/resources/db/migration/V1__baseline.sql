-- BookWorm baseline schema. Must stay in sync with the JPA entities (verified by PostgresSchemaTest).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    gift_points   INTEGER      NOT NULL,
    version       BIGINT       NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'ADMIN'))
);

CREATE TABLE categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE publishers (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    CONSTRAINT uk_publishers_name UNIQUE (name)
);

CREATE TABLE books (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                   VARCHAR(255)             NOT NULL,
    author                  VARCHAR(255)             NOT NULL,
    isbn                    VARCHAR(20),
    description             TEXT,
    price                   NUMERIC(10, 2)           NOT NULL,
    format                  VARCHAR(20)              NOT NULL,
    language                VARCHAR(50)              NOT NULL,
    cover_image_url         VARCHAR(500),
    stock_quantity          INTEGER                  NOT NULL,
    estimated_delivery_days INTEGER                  NOT NULL,
    average_rating          DOUBLE PRECISION         NOT NULL,
    total_reviews           INTEGER                  NOT NULL,
    copies_sold             INTEGER                  NOT NULL,
    category_id             BIGINT                   NOT NULL,
    publisher_id            BIGINT                   NOT NULL,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    version                 BIGINT                   NOT NULL,
    CONSTRAINT uk_books_isbn UNIQUE (isbn),
    CONSTRAINT ck_books_format CHECK (format IN ('PAPERBACK', 'HARDCOVER', 'EBOOK')),
    CONSTRAINT fk_books_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_books_publisher FOREIGN KEY (publisher_id) REFERENCES publishers (id)
);

CREATE INDEX idx_books_category ON books (category_id);
CREATE INDEX idx_books_publisher ON books (publisher_id);
CREATE INDEX idx_books_created_at ON books (created_at);

CREATE TABLE addresses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    first_name  VARCHAR(50)  NOT NULL,
    last_name   VARCHAR(50)  NOT NULL,
    street      VARCHAR(255) NOT NULL,
    city        VARCHAR(100) NOT NULL,
    state       VARCHAR(100),
    postal_code VARCHAR(10)  NOT NULL,
    country     VARCHAR(100) NOT NULL,
    phone       VARCHAR(20)  NOT NULL,
    email       VARCHAR(255),
    CONSTRAINT fk_addresses_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_addresses_user ON addresses (user_id);

CREATE TABLE carts (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_carts_user UNIQUE (user_id),
    CONSTRAINT fk_carts_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE cart_items (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id  BIGINT  NOT NULL,
    book_id  BIGINT  NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT uk_cart_items_cart_book UNIQUE (cart_id, book_id),
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts (id),
    CONSTRAINT fk_cart_items_book FOREIGN KEY (book_id) REFERENCES books (id)
);

CREATE INDEX idx_cart_items_book ON cart_items (book_id);

CREATE TABLE orders (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT                   NOT NULL,
    address_id           BIGINT                   NOT NULL,
    status               VARCHAR(20)              NOT NULL,
    subtotal             NUMERIC(10, 2)           NOT NULL,
    tax                  NUMERIC(10, 2)           NOT NULL,
    delivery_charges     NUMERIC(10, 2)           NOT NULL,
    discount             NUMERIC(10, 2)           NOT NULL,
    total_amount         NUMERIC(10, 2)           NOT NULL,
    gift_points_redeemed INTEGER                  NOT NULL,
    gift_points_earned   INTEGER                  NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    version              BIGINT                   NOT NULL,
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING_PAYMENT', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_orders_address FOREIGN KEY (address_id) REFERENCES addresses (id)
);

CREATE INDEX idx_orders_user_created ON orders (user_id, created_at);
CREATE INDEX idx_orders_address ON orders (address_id);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    book_id    BIGINT         NOT NULL,
    quantity   INTEGER        NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_items_book FOREIGN KEY (book_id) REFERENCES books (id)
);

CREATE INDEX idx_order_items_order ON order_items (order_id);
CREATE INDEX idx_order_items_book ON order_items (book_id);

CREATE TABLE payments (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id              BIGINT         NOT NULL,
    method                VARCHAR(20)    NOT NULL,
    status                VARCHAR(20)    NOT NULL,
    amount                NUMERIC(10, 2) NOT NULL,
    transaction_reference VARCHAR(30),
    CONSTRAINT uk_payments_order UNIQUE (order_id),
    CONSTRAINT ck_payments_method CHECK (method IN ('CREDIT_CARD', 'DEBIT_CARD', 'UPI', 'WALLET')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id)
);

CREATE TABLE reviews (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id    BIGINT                   NOT NULL,
    user_id    BIGINT                   NOT NULL,
    rating     INTEGER                  NOT NULL,
    comment    VARCHAR(1000)            NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_reviews_book_user UNIQUE (book_id, user_id),
    CONSTRAINT fk_reviews_book FOREIGN KEY (book_id) REFERENCES books (id),
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_reviews_book_created ON reviews (book_id, created_at);
CREATE INDEX idx_reviews_user ON reviews (user_id);
